#!/usr/bin/env python3
"""Write the weekly report of changes merged into the main branch.

For a period (default: the last 7 days), lists:
- each change merged into the main branch, with its author and the domains it touched;
- concepts added, definitions changed, relationships and ambiguities added or changed,
  each grouped by domain;
- progress of the questions for our firm per domain (answered at the start and at the end);
- shared files changed (tools, agent setup, classification, documentation), for the Ontology Lead;
- the change-log entries added.

Writes reports/weekly/<end date>.md and prints its path. Commit it, or paste it in the
team channel.

Usage: python3 tools/weekly_report.py [--days N] [--since YYYY-MM-DD] [--branch REF] [--stdout]
"""
import datetime
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import build_domain_views as bdv  # noqa: E402
import pr_scope  # noqa: E402

from openpyxl import load_workbook  # noqa: E402


def git(*args, check=True):
    return subprocess.run(["git", *args], cwd=ROOT, check=check, capture_output=True, text=True).stdout


def option(args, name, default=None):
    if name in args:
        return args[args.index(name) + 1]
    return default


def show(commit, path):
    return subprocess.run(["git", "show", f"{commit}:{path}"], cwd=ROOT, capture_output=True, text=True).stdout


def rows_by_id(text, marker):
    out = {}
    for head, rows in bdv.tables(text):
        if marker in head:
            for r in rows:
                if r.get("ID"):
                    out[r["ID"]] = r
    return out


def answered(commit, page):
    """(questions, answered) in the domain workbook at a commit."""
    blob = subprocess.run(["git", "show", f"{commit}:domains/{page}/questions-for-experts.xlsx"],
                          cwd=ROOT, capture_output=True).stdout
    if not blob:
        return 0, 0
    with tempfile.NamedTemporaryFile(suffix=".xlsx", delete=False) as f:
        f.write(blob)
        path = f.name
    try:
        wb = load_workbook(path, read_only=True, data_only=True)
        sheet = "1 Questions for our firm"
        rows = [r for r in wb[sheet].iter_rows(min_row=5, values_only=True) if r and r[0] is not None] \
            if sheet in wb.sheetnames else []
        wb.close()
    finally:
        os.unlink(path)
    done = sum(1 for r in rows if len(r) > 9 and (r[9] in ("Answered", "Not applicable")))
    return len(rows), done


def main(argv):
    os.chdir(ROOT)
    branch = option(argv, "--branch") or next(
        (r for r in ("origin/main", "main") if git("rev-parse", "--verify", "-q", r, check=False).strip()), None)
    if not branch:
        raise SystemExit("No main branch found; pass --branch")
    end_day = datetime.date.today()
    since = option(argv, "--since")
    start_day = datetime.date.fromisoformat(since) if since else end_day - datetime.timedelta(
        days=int(option(argv, "--days", "7")))
    end = git("rev-parse", branch).strip()
    start = git("rev-list", "-1", f"--before={start_day.isoformat()} 00:00", branch).strip()
    if not start:
        start = git("rev-list", "--max-parents=0", branch).splitlines()[-1]

    data = bdv.load()
    primary, _, owner = pr_scope.domain_maps(data)
    name = {i: c["Canonical English name"] for i, c in data["concepts"].items()}

    def label(i):
        return f"{name.get(i, i)} ({i})"

    out = [f"# Weekly ontology report, {start_day.isoformat()} to {end_day.isoformat()}", "",
           f"Generated by `tools/weekly_report.py` from the main branch ({end[:7]}). "
           "Merged changes are Draft proposals; approvals are recorded in the decision log.", ""]

    # Merged changes
    commits = [c for c in git("rev-list", "--first-parent", f"{start}..{end}").splitlines() if c]
    out += ["## Changes merged", ""]
    if not commits:
        out += ["Nothing was merged this week.", ""]
    shared = set()
    for c in reversed(commits):
        author, date, subject = git("show", "-s", "--format=%an%x1f%ad%x1f%s", "--date=short", c).split("\x1f")
        body = [b for b in git("show", "-s", "--format=%b", c).splitlines() if b.strip()]
        title = subject.strip()
        if re.match(r"(Merge|Merged) ", title) and body:
            title = f"{body[0].strip()} ({title})"
        parent = f"{c}^1"
        _, touched, comment, lead, unknown = pr_scope.classify(parent, c, data)
        shared |= set(lead)
        doms = ", ".join(sorted(touched)) or "no domain"
        extra = f"; also shown in {', '.join(sorted(comment))}" if comment else ""
        new = f"; {len(unknown)} new concept(s)" if unknown else ""
        out.append(f"- {date}, {author}: {title}. Domains: {doms}{extra}{new}.")
    out.append("")

    # Concepts, relationships, ambiguities
    before_c = rows_by_id(show(start, "ontology/foundation.md"), "Working business definition")
    after_c = rows_by_id(show(end, "ontology/foundation.md"), "Working business definition")
    added = [i for i in after_c if i not in before_c]
    changed = [i for i in after_c if i in before_c
               and after_c[i].get("Working business definition") != before_c[i].get("Working business definition")]
    renamed = [i for i in after_c if i in before_c
               and after_c[i].get("Canonical English name") != before_c[i].get("Canonical English name")]
    removed = [i for i in before_c if i not in after_c]

    def by_domain(ids):
        groups = {}
        for i in ids:
            groups.setdefault(primary.get(i, "no primary domain yet"), []).append(i)
        return groups

    out += ["## Concepts", ""]
    for title, ids in (("Added", added), ("Definition changed", changed), ("Renamed", renamed),
                       ("Removed from the catalogue (IDs are never reused)", removed)):
        if not ids:
            continue
        out += [f"### {title}: {len(ids)}", ""]
        for dom, group in sorted(by_domain(ids).items()):
            out.append(f"- **{dom}**: " + "; ".join(label(i) for i in group))
        out.append("")
    if not (added or changed or renamed or removed):
        out += ["No concept added or changed.", ""]

    before_r = rows_by_id(show(start, "relationships/relationships.md"), "Relation")
    after_r = rows_by_id(show(end, "relationships/relationships.md"), "Relation")
    before_a = rows_by_id(show(start, "governance/ambiguity-register.md"), "Affected IDs")
    after_a = rows_by_id(show(end, "governance/ambiguity-register.md"), "Affected IDs")
    r_new = [i for i in after_r if i not in before_r]
    r_mod = [i for i in after_r if i in before_r and after_r[i] != before_r[i]]
    a_new = [i for i in after_a if i not in before_a]
    a_mod = [i for i in after_a if i in before_a and after_a[i] != before_a[i]]
    out += ["## Relationships and ambiguities", "",
            f"- Relationships added: {len(r_new)}, changed: {len(r_mod)}",
            f"- Ambiguities added: {len(a_new)}, changed: {len(a_mod)}"]
    listed = a_new + a_mod
    for i in listed[:15]:
        out.append(f"  - {after_a[i].get('Term / issue', '')} ({i}): {after_a[i].get('Status', '')}")
    if len(listed) > 15:
        out.append(f"  - and {len(listed) - 15} more")
    out.append("")

    # Answers
    out += ["## Questions for our firm", "", "| Domain | Owner | Questions | Answered at start | Answered now |",
            "|---|---|---|---|---|"]
    for dom in data["domains"]:
        page = dom["Page"]
        total, now = answered(end, page)
        _, then = answered(start, page)
        mark = " (+%d)" % (now - then) if now > then else ""
        out.append(f"| {page} | {owner.get(page, '')} | {total} | {then} | {now}{mark} |")
    out.append("")

    # Shared files
    out += ["## Shared files changed (for the Ontology Lead)", ""]
    out += [f"- {f}" for f in sorted(shared)] or ["None."]
    out.append("")

    # Change log
    diff = git("diff", f"{start}..{end}", "--", "CHANGELOG.md")
    entries = [line[1:].strip() for line in diff.splitlines()
               if line.startswith("+- ") or line.startswith("+  - ")]
    out += ["## Change-log entries added", ""]
    out += [f"- {e.lstrip('- ').strip()}" for e in entries] or ["None."]
    report = "\n".join(out).rstrip() + "\n"

    if "--stdout" in argv:
        sys.stdout.write(report)
        return 0
    folder = os.path.join(ROOT, "reports", "weekly")
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, f"{end_day.isoformat()}.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(report)
    print(os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
