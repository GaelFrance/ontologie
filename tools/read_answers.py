#!/usr/bin/env python3
"""Turn the experts' workbook of a domain into a Markdown page that AI agents can read.

AI agents cannot read Excel files. This script reads
domains/<page>/questions-for-experts.xlsx and writes .review-notes/answers/<page>.md
(not committed): every question with its answer, status, follow-up and the
initials of the expert who answered; the expert views on words with several
meanings; and, at the top, what is unanswered, disputed or left in conflict
after a merge.

Usage (needs openpyxl):
  python3 tools/read_answers.py PAGE [PAGE ...]   one or more domain folder names
  python3 tools/read_answers.py all               every domain
  add --stdout to print the page instead of writing the file
"""
import os
import re
import sys

from openpyxl import load_workbook

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKBOOK = "questions-for-experts.xlsx"
OUT = os.path.join(ROOT, ".review-notes", "answers")


def pages():
    base = os.path.join(ROOT, "domains")
    return sorted(d for d in os.listdir(base) if os.path.isfile(os.path.join(base, d, WORKBOOK)))


def text(value):
    return re.sub(r"\s+", " ", str(value)).strip() if value not in (None, "") else ""


def rows(wb, sheet):
    if sheet not in wb.sheetnames:
        return []
    return [[text(v) for v in list(r) + [None] * 14]
            for r in wb[sheet].iter_rows(min_row=5, values_only=True) if r and r[0] is not None]


def cover(wb):
    if "Start here" not in wb.sheetnames:
        return {}
    return {text(k): text(v) for k, v in wb["Start here"].iter_rows(min_col=1, max_col=2, values_only=True)
            if k and text(v)}


def render(page):
    wb = load_workbook(os.path.join(ROOT, "domains", page, WORKBOOK), read_only=True, data_only=True)
    firm = rows(wb, "1 Questions for our firm")
    role = rows(wb, "2 Questions by role")
    meaning = rows(wb, "3 Meaning to confirm")
    info = cover(wb)
    wb.close()

    answered = [r for r in firm if r[8] or r[9]]
    conflicts = [r for r in firm + meaning if any("CONFLICT" in c for c in r)]
    dissent = [r for r in meaning if r[4] in ("Disagree", "Unsure")]
    unsigned = [r for r in answered if not r[12]]
    p1_open = [r for r in firm if r[1] == "1" and r[9] not in ("Answered", "Not applicable")]

    out = [f"# Answers from the experts: {page}", "",
           f"Generated by `tools/read_answers.py` from `domains/{page}/{WORKBOOK}`; do not edit. "
           "Answers describe how our firm works: they inform the definitions, which stay generic.", ""]
    for label in ("Interviewer", "Expert (name and role)", "Date of the session"):
        if info.get(label):
            out.append(f"- {label}: {info[label]}")
    out += [f"- Questions for our firm: {len(firm)}, with an answer: {len(answered)}, "
            f"priority 1 still open: {len(p1_open)}",
            f"- Answers without the expert's initials: {len(unsigned)}",
            f"- Meanings an expert disagrees with or is unsure of: {len(dissent)}",
            f"- Cells left in CONFLICT after a merge (resolve them in Excel first): {len(conflicts)}", ""]

    out += ["## 1. Questions for our firm", ""]
    for r in firm:
        ref = f" ({r[11]})" if r[11] else ""
        out += [f"### {r[0]}. {r[2]}{ref}", f"Priority {r[1]}." if r[1] else "", ""]
        if not (r[8] or r[9] or r[10]):
            out += ["- Not answered yet.", ""]
            continue
        who = r[12] or "initials missing"
        out.append(f"- **Answer** ({who}): {r[8] or '(no answer text)'}")
        if r[9]:
            out.append(f"- **Status**: {r[9]}")
        if r[10]:
            out.append(f"- **Follow-up**: {r[10]}")
        out.append("")

    out += ["## 2. Notes on the questions put to each role", ""]
    noted = [r for r in role if r[3]]
    if not noted:
        out += ["No notes yet.", ""]
    for r in noted:
        out += [f"### {r[1]}: {r[2]}", "", r[3], ""]

    out += ["## 3. Words with several meanings", ""]
    for r in meaning:
        flag = " **Expert disagrees or is unsure.**" if r in dissent else ""
        out += [f"### {r[1]} ({r[6]}){flag}", "", f"Proposed answer: {r[3]}", ""]
        if not (r[4] or r[5]):
            out += ["- No view yet.", ""]
            continue
        who = r[7] or "initials missing"
        out.append(f"- **View** ({who}): {r[4] or '(none)'}" + (f". {r[5]}" if r[5] else ""))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv):
    to_stdout = "--stdout" in argv
    wanted = [a for a in argv if not a.startswith("--")]
    known = pages()
    if not wanted:
        raise SystemExit(__doc__)
    if wanted == ["all"]:
        wanted = known
    for page in wanted:
        if page not in known:
            raise SystemExit(f"Unknown domain '{page}'. Use one of: {', '.join(known)}")
        page_text = render(page)
        if to_stdout:
            sys.stdout.write(page_text)
            continue
        os.makedirs(OUT, exist_ok=True)
        path = os.path.join(OUT, f"{page}.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(page_text)
        print(os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main(sys.argv[1:])
